def _appels_metric(page: Path):
    for noeud in ast.walk(ast.parse(page.read_text(encoding="utf-8"))):
        if isinstance(noeud, ast.Call) and isinstance(noeud.func, ast.Attribute) and noeud.func.attr == "metric":
            valeur = noeud.args[1] if len(noeud.args) > 1 else next(
                (k.value for k in noeud.keywords if k.arg == "value"), None
            )
            yield noeud.lineno, valeur


@pytest.mark.parametrize("page", PAGES, ids=lambda p: p.name)
def test_aucune_fausse_metrique_codee_en_dur(page):
    for ligne, valeur in _appels_metric(page):
        if isinstance(valeur, ast.Constant):
            assert not isinstance(valeur.value, (int, float)), f"{page.name}:{ligne} métrique numérique codée en dur"
            assert not re.search(r"\d", str(valeur.value)), f"{page.name}:{ligne} métrique chiffrée codée en dur"


