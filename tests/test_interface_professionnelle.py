WIDGETS_A_LIBELLE = {
    "button", "form_submit_button", "download_button", "text_input", "number_input", "selectbox",
    "multiselect", "checkbox", "radio", "file_uploader", "text_area", "date_input", "toggle", "slider",
}


def _texte_de(noeud):
    if isinstance(noeud, ast.Constant) and isinstance(noeud.value, str):
        return noeud.value
    if isinstance(noeud, ast.JoinedStr):
        return "".join(v.value for v in noeud.values if isinstance(v, ast.Constant) and isinstance(v.value, str))
    return None


@pytest.mark.parametrize("source", SOURCES_INTERFACE, ids=_ids)
def test_widgets_ont_un_libelle_explicite(source):
    for noeud in ast.walk(ast.parse(source.read_text(encoding="utf-8"))):
        if not (isinstance(noeud, ast.Call) and isinstance(noeud.func, ast.Attribute)):
            continue
        if noeud.func.attr not in WIDGETS_A_LIBELLE:
            continue
        for mot_cle in noeud.keywords:
            if mot_cle.arg == "label_visibility":
                assert _texte_de(mot_cle.value) != "collapsed", f"{_ids(source)}:{noeud.lineno} libellé masqué"
        if not noeud.args:
            continue
        texte = _texte_de(noeud.args[0])
        if texte is None:  # libellé calculé (variable, expression) : vérifié à l'exécution
            continue
        assert len(re.findall(r"[A-Za-zÀ-ÿ]", texte)) >= 3 or isinstance(noeud.args[0], ast.JoinedStr), (
            f"{_ids(source)}:{noeud.lineno} libellé non explicite : {texte!r}"
        )


def test_champs_mot_de_passe_masques():
    for source in SOURCES_INTERFACE:
        for noeud in ast.walk(ast.parse(source.read_text(encoding="utf-8"))):
            if isinstance(noeud, ast.Call) and isinstance(noeud.func, ast.Attribute) and noeud.func.attr == "text_input":
                libelle = _texte_de(noeud.args[0]) if noeud.args else ""
                if libelle and "mot de passe" in libelle.lower():
                    types = [_texte_de(k.value) for k in noeud.keywords if k.arg == "type"]
                    assert types == ["password"], f"{_ids(source)}:{noeud.lineno} mot de passe non masqué"


